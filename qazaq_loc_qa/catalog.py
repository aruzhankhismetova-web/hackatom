def suggestions_for(language: str) -> dict[str, str]:
    field = f"{language}_fixed"
    return {row["key"]: row[field] for row in STRINGS}


def bundle_from_catalog(*, fixed_languages: tuple[str, ...] = ()) -> Bundle:
    """Собрать бандл. fixed_languages подменяют язык эталоном."""
    segments: list[Segment] = []
    for row in STRINGS:
        texts = {
            "en": row["en"],
            "ru": row["ru"],
            "kk": row["kk_fixed"] if "kk" in fixed_languages else row["kk"],
            "uz": row["uz_fixed"] if "uz" in fixed_languages else row["uz"],
        }
        segments.append(
            Segment(
                key=row["key"],
                texts=texts,
                context=row["context"],
                source_file="catalog",
            )
        )
    return Bundle(segments=segments, source_language="en", origin="catalog")


def suggestion_map() -> dict[tuple[str, str], str]:
    mapped: dict[tuple[str, str], str] = {}
    for row in STRINGS:
        mapped[("kk", row["key"])] = row["kk_fixed"]
        mapped[("uz", row["key"])] = row["uz_fixed"]
    return mapped
